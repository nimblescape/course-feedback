// Writes jsr-modules.d.ts: one module declaration per export of the installed
// @jsr/* packages, so that tsc knows `jsr:@std/fmt/colors` and its types.
import fs from "node:fs";
const tools = new URL("./", import.meta.url);
const lines = ["// Generated by jsr-types.mjs"];
const dir = new URL("node_modules/@jsr/", tools);
for (const folder of fs.existsSync(dir) ? fs.readdirSync(dir).sort() : []) {
  const [scope, name] = folder.split("__");
  const manifest = JSON.parse(fs.readFileSync(new URL(`${folder}/package.json`, dir), "utf8"));
  for (const path of Object.keys(manifest.exports ?? { ".": "" }).sort()) {
    const sub = path === "." ? "" : path.slice(1);
    lines.push(`declare module "jsr:@${scope}/${name}${sub}" {`, `  export * from "@jsr/${folder}${sub}";`, "}");
  }
}
fs.writeFileSync(new URL("jsr-modules.d.ts", tools), `${lines.join("\n")}\n`);
